def write_txt(name: str, doc: dict) -> Path:
    lines = [doc["title"], *doc["body"]]
    path = OUT_DIR / name
    path.write_text("\n".join(lines), encoding="utf-8")
    return path


def write_docx(name: str, doc: dict) -> Path:
    from docx import Document

    document = Document()
    document.add_heading(doc["title"], level=0)
    for paragraph in doc["body"]:
        document.add_paragraph(paragraph)
    path = OUT_DIR / name
    document.save(path)
    return path


def main() -> None:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    for doc, stem in ((PURCHASE, "采购合同样例"), (DEVELOP, "软件委托开发合同样例")):
        txt = write_txt(f"{stem}.txt", doc)
        docx = write_docx(f"{stem}.docx", doc)
        print(f"generated: {txt.name} / {docx.name}")


if __name__ == "__main__":
    main()
